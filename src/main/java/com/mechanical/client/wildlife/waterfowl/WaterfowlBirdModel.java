/**
 * Mallard and Mute Swan: the flock-bird model (BirdModel: walking, swimming, roosting, flight, carcass poses) with two
 * extras. A mallard on the water now and then tips up to dabble, tail in the air and head under; a swan defending its
 * nest raises its arched wings over the back ("busking") and draws its neck back, ready to lunge.
 * Geometry and textures: scripts/gen_small_models.py (SmallGeometry); the createXxxLayer methods below delegate there
 * (that script rewrites them; the older texture script named in the marker runs it at its end).
 */
public class WaterfowlBirdModel extends BirdModel {
    public static final ModelLayerLocation MALLARD = layer("mallard");
    public static final ModelLayerLocation MUTE_SWAN = layer("mute_swan");

    private final ModelPart body, neck, head, leftWing, rightWing, tail;

    public WaterfowlBirdModel(ModelPart root, float flightNeck, float beat) {
        super(root, flightNeck, beat);
        body = root.getChild("body");
        neck = body.getChild("neck");
        head = neck.getChild("head");
        leftWing = body.getChild("left_wing");
        rightWing = body.getChild("right_wing");
        tail = body.getChild("tail");
    }

    private static ModelLayerLocation layer(String name) {
        return new ModelLayerLocation(Identifier.fromNamespaceAndPath("mechanical", name), "main");
    }

    @Override
    public void setupAnim(WildAnimalRenderState state) {
        super.setupAnim(state);
        if (CarcassRenderer.isCarcass(state) || CarcassRenderer.isHung(state) || state.flying || state.dozing) return;
        WaterfowlRenderState s = (WaterfowlRenderState) state;
        float d = s.dabble;
        if (d > 0.0F) {
            // bottoms up: the body tips forward round its middle, tail high, head and neck reaching down under the water
            body.xRot += 1.45F * d;
            body.y += 1.0F * d;
            neck.xRot += 0.35F * d;
            tail.xRot += 0.5F * d;
            leftWing.zRot = rightWing.zRot = 0.0F;
        }
        if (state.charging) {
            // threat display: wings half raised and arched over the back, neck drawn back into an S, bill down
            float quiver = Mth.sin(state.ageInTicks * 1.3F) * 0.04F;
            leftWing.zRot = -0.95F - quiver;
            rightWing.zRot = 0.95F + quiver;
            leftWing.xRot = rightWing.xRot = -0.35F;
            neck.xRot = -0.55F;
            head.xRot = 0.85F;
            head.yRot = 0.0F;
        }
    }

    // BEGIN GENERATED by scripts/gen_fauna_waterfowl_textures.py
    public static LayerDefinition createMallardLayer() {
        return com.mechanical.client.wildlife.SmallGeometry.mallard();
    }

    public static LayerDefinition createMuteSwanLayer() {
        return com.mechanical.client.wildlife.SmallGeometry.muteSwan();
    }
    // END GENERATED
}
