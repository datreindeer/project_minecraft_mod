/**
 * Mallard and Mute Swan: the flock-bird model (BirdModel: walking, swimming, roosting, flight, carcass poses) with two
 * extras. A mallard on the water now and then tips up to dabble, tail in the air and head under; a swan defending its
 * nest raises its arched wings over the back ("busking") and draws its neck back, ready to lunge.
 * Geometry and textures: scripts/gen_fauna_waterfowl_textures.py, which writes the createXxxLayer methods below.
 */
